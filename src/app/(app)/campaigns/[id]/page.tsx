import Link from "next/link";
import { notFound } from "next/navigation";
import { CheckCircle2, FileCheck2, Pause, Pencil, Play, RefreshCw, Sparkles, Trash2, XCircle } from "lucide-react";
import { applyCorrectedDraft, deleteCampaign, reviewCampaign, setCampaignStatus, verifyCampaignAction } from "@/app/actions";
import { Flash, type SP } from "@/components/Flash";
import { FindingsReport } from "@/components/FindingsReport";
import { Card, CHANNEL_LABELS, DemoBadge, EmptyState, fmtDate, KeyValue, Notice, PageHeader, Pill, RiskBadge } from "@/components/ui";
import type { CorrectedCopy } from "@/lib/ai/schemas";
import { parseJson, prisma } from "@/lib/db";
import { formatMoney } from "@/lib/money";
import type { ClaimAnalysis } from "@/lib/verification/types";

export default async function CampaignDetail({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: SP }) {
  const { id } = await params;
  const c = await prisma.campaign.findUnique({
    where: { id },
    include: { store: true, product: true, variant: true, checks: { orderBy: { createdAt: "desc" }, include: { findings: true } }, approvals: { orderBy: { createdAt: "desc" } } },
  });
  if (!c) notFound();
  const latest = c.checks[0];
  const snapshot = parseJson<{ scoreBreakdown?: { code: string; severity: string; points: number }[]; claims?: ClaimAnalysis[] }>(latest?.factsSnapshotJson, {});
  const copy = parseJson<CorrectedCopy | null>(c.correctedDraftJson, null);
  const claims = parseJson<string[]>(c.claimsJson, []);
  const cur = c.store.currency;

  return (
    <>
      <PageHeader
        eyebrow={`Campaign Guardian · ${CHANNEL_LABELS[c.channel]}`}
        title={c.name}
        subtitle={<span className="flex flex-wrap items-center gap-2"><Pill>{c.status}</Pill><DemoBadge show={c.isDemo} /><span>Last verified {fmtDate(c.lastCheckedAt, true)}</span></span>}
        actions={
          <>
            <form action={verifyCampaignAction}><input type="hidden" name="id" value={c.id} /><button className="btn btn-primary"><RefreshCw size={15} />Re-verify now</button></form>
            <Link href={`/campaigns/${c.id}/edit`} className="btn btn-secondary"><Pencil size={15} />Edit</Link>
            {latest && <Link href={`/reports/${latest.id}`} className="btn btn-secondary"><FileCheck2 size={15} />Report</Link>}
          </>
        }
      />
      <Flash searchParams={searchParams} />

      <div className="grid gap-6 xl:grid-cols-3">
        <div className="space-y-6 xl:col-span-2">
          <Card>
            <div className="flex flex-col gap-5 sm:flex-row sm:items-center sm:justify-between">
              <div>
                <div className="label">Verification result</div>
                <div className="flex items-center gap-3"><RiskBadge status={c.riskStatus} size="lg" /><span className="text-sm text-muted">{latest?.summary ?? "This campaign has not been verified yet."}</span></div>
              </div>
              <div className="text-right">
                <div className="label">Risk score</div>
                <div className="h-display text-4xl tabular-nums">{c.riskScore ?? "—"}<span className="text-base text-steel">/100</span></div>
              </div>
            </div>
            {snapshot.scoreBreakdown && snapshot.scoreBreakdown.length > 0 && (
              <details className="mt-4 rounded-lg bg-cloud px-4 py-3 text-xs">
                <summary className="cursor-pointer font-semibold text-ink">How the score is calculated</summary>
                <p className="mt-2 text-muted">Each non-passing finding adds points by severity (low 5, medium 12, high 25, critical 40), capped at 100. The status comes from the findings themselves: any BLOCK finding blocks the campaign, whatever the score.</p>
                <ul className="mt-2 grid gap-1 sm:grid-cols-2">{snapshot.scoreBreakdown.map((b, i) => <li key={i} className="flex justify-between gap-2"><code>{b.code}</code><span>{b.severity} · +{b.points}</span></li>)}</ul>
              </details>
            )}
            {latest?.aiProvider && <p className="mt-3 text-[11px] text-steel">Claim analysis: {latest.aiProvider}. Prices, stock, dates and URLs are always checked deterministically.</p>}
          </Card>

          <Card title="Findings" subtitle="Every finding shows its source evidence" >
            {latest ? <FindingsReport findings={latest.findings} /> : <EmptyState title="Not verified yet" body="Run verification to compare this campaign with live store facts." />}
          </Card>

          {copy && c.riskStatus !== "PASS" && (
            <Card title={<span className="flex items-center gap-2"><Sparkles size={15} className="text-brass" />Corrected campaign draft</span>} subtitle={`Generated by: ${copy.generator}. Grounded only in approved facts, live prices and merchant policies.`}
              actions={<form action={applyCorrectedDraft}><input type="hidden" name="id" value={c.id} /><button className="btn btn-accent btn-sm">Apply as new draft</button></form>}>
              <div className="grid gap-4 md:grid-cols-2">
                <div className="rounded-lg border border-line p-4"><div className="label">Original headline</div><p className="text-sm text-muted line-through decoration-block/40">{c.headline || "—"}</p><div className="label mt-3">Original text</div><p className="whitespace-pre-line text-sm text-muted">{c.promoText || "—"}</p></div>
                <div className="rounded-lg border border-teal/40 bg-teal/5 p-4"><div className="label">Corrected headline</div><p className="text-sm font-medium">{copy.headline}</p><div className="label mt-3">Corrected text</div><p className="whitespace-pre-line text-sm">{copy.marketingText}</p><div className="label mt-3">Suggested CTA</div><p className="text-sm">{copy.cta}</p></div>
              </div>
              <div className="mt-4"><div className="label">Corrected product description</div><p className="text-sm">{copy.productDescription}</p></div>
              <div className="mt-4 rounded-lg bg-cloud px-4 py-3 text-xs text-muted"><b className="text-ink">Explanation.</b> {copy.explanation}{copy.guardNotes.length > 0 && <ul className="mt-2 list-disc pl-4">{copy.guardNotes.map((n, i) => <li key={i}>{n}</li>)}</ul>}</div>
              <p className="mt-3 text-[11px] text-steel">Applying the draft only updates this campaign record. PromiSure AI never publishes posts or changes ads.</p>
            </Card>
          )}

          {snapshot.claims && snapshot.claims.length > 0 && (
            <Card title="Claim analysis" pad={false}>
              <div className="overflow-x-auto">
                <table className="table">
                  <thead><tr><th>Claim</th><th>Classification</th><th>Reason</th><th>Analyzer</th></tr></thead>
                  <tbody>{snapshot.claims.map((a, i) => (
                    <tr key={i}><td className="min-w-48">{a.claim}</td><td><Pill tone={a.classification === "SUPPORTED" ? "pass" : a.classification === "CONTRADICTED" ? "block" : "review"}>{a.classification}</Pill></td><td className="min-w-64 text-muted">{a.reason}</td><td className="text-xs text-muted">{a.analyzer}</td></tr>
                  ))}</tbody>
                </table>
              </div>
            </Card>
          )}
        </div>

        <div className="space-y-6">
          <Card title="Human review">
            {c.riskStatus === "BLOCK" && <Notice tone="danger">Approval is unavailable while BLOCK findings remain. Fix the campaign or the store, then re-verify.</Notice>}
            {c.riskStatus === "REVIEW" && <Notice tone="warn">Open items need human verification. Approval requires a note explaining how they were checked.</Notice>}
            <form action={reviewCampaign} className="mt-3 space-y-3">
              <input type="hidden" name="id" value={c.id} />
              <div><label className="label" htmlFor="note">Reviewer note</label><textarea id="note" name="note" className="input min-h-20" placeholder="e.g. Confirmed with warehouse that 40 units arrive Monday." /></div>
              <div className="flex flex-wrap gap-2">
                <button name="decision" value="APPROVED" className="btn btn-primary btn-sm" disabled={c.riskStatus === "BLOCK" || !latest}><CheckCircle2 size={14} />Approve</button>
                <button name="decision" value="CHANGES_REQUESTED" className="btn btn-secondary btn-sm">Request changes</button>
                <button name="decision" value="REJECTED" className="btn btn-danger btn-sm"><XCircle size={14} />Reject</button>
              </div>
            </form>
            {["APPROVED", "LIVE", "PAUSED"].includes(c.status) && (
              <form action={setCampaignStatus} className="mt-4 border-t border-line pt-4">
                <input type="hidden" name="id" value={c.id} />
                <p className="mb-2 text-xs text-muted">Record the campaign&apos;s launch state. This changes nothing on ad platforms.</p>
                {c.status === "LIVE" ? <button name="status" value="PAUSED" className="btn btn-secondary btn-sm"><Pause size={14} />Mark paused</button> : <button name="status" value="LIVE" className="btn btn-secondary btn-sm"><Play size={14} />Mark live</button>}
              </form>
            )}
            {c.approvals.length > 0 && (
              <ul className="mt-4 space-y-2 border-t border-line pt-4">
                {c.approvals.map((a) => (
                  <li key={a.id} className="text-xs"><div className="flex items-center gap-2"><Pill tone={a.decision === "APPROVED" ? "pass" : a.decision === "REJECTED" ? "block" : "review"}>{a.decision}</Pill><span className="text-muted">{fmtDate(a.createdAt, true)}</span></div><div className="mt-1 text-muted">{a.reviewer} · risk at decision: {a.riskStatusAtDecision ?? "—"}</div>{a.note && <div className="mt-0.5 text-ink">“{a.note}”</div>}</li>
                ))}
              </ul>
            )}
          </Card>

          <Card title="Campaign details">
            <KeyValue items={[
              ["Product", c.product ? <Link href={`/products/${c.product.id}`} className="link">{c.product.title}</Link> : "—"],
              ["Variant", c.variant ? `${c.variant.title}${c.variant.sku ? ` · ${c.variant.sku}` : ""}` : "—"],
              ["Advertised price", c.advertisedPrice ? formatMoney(c.advertisedPrice, cur) : "—"],
              ["Live price", c.variant ? formatMoney(c.variant.price, cur) : "—"],
              ["Discount", c.discountType === "NONE" ? "None" : `${c.discountType.replace("_", " ").toLowerCase()} ${c.discountValue ?? ""}`],
              ["Window", `${fmtDate(c.startsAt)} → ${fmtDate(c.endsAt)}`],
              ["Delivery promise", c.deliveryPromise || "—"],
              ["Destination", c.productUrl ? <span className="break-all text-xs">{c.productUrl}</span> : "—"],
            ]} />
            <div className="mt-4"><div className="label">Claims</div>{claims.length ? <ul className="list-disc pl-4 text-sm">{claims.map((cl) => <li key={cl}>{cl}</li>)}</ul> : <p className="text-sm text-muted">None listed</p>}</div>
          </Card>

          <Card title="Original submission">
            <details className="text-xs"><summary className="cursor-pointer text-muted">View stored original content</summary><pre className="mt-2 max-h-72 overflow-auto whitespace-pre-wrap rounded bg-cloud p-3 text-[11px]">{JSON.stringify(parseJson(c.originalSnapshot, {}), null, 2)}</pre></details>
          </Card>

          <Card title="Verification history" pad={false}>
            <ul className="divide-y divide-line">
              {c.checks.slice(0, 10).map((k) => (
                <li key={k.id} className="flex items-center justify-between px-5 py-2.5 text-sm"><Link href={`/reports/${k.id}`} className="flex items-center gap-2 hover:text-teal-dark"><RiskBadge status={k.riskStatus} /><span className="text-xs text-muted">{k.trigger}</span></Link><span className="text-xs text-muted">{fmtDate(k.createdAt, true)}</span></li>
              ))}
              {c.checks.length === 0 && <li className="px-5 py-3 text-sm text-muted">No checks yet.</li>}
            </ul>
          </Card>

          <form action={deleteCampaign}><input type="hidden" name="id" value={c.id} /><button className="btn btn-danger btn-sm w-full"><Trash2 size={14} />Delete campaign</button></form>
        </div>
      </div>
    </>
  );
}
